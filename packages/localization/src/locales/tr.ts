/**
 * Katalog `as const` ile yazıldığı için değerler harfi harfine tiplenir.
 * Diğer diller aynı anahtarlara sahip olmalı ama farklı metin içerebilmeli;
 * bu yüzden metin tiplerini `string`'e genişletiriz.
 */
type WidenStrings<T> = {
  [K in keyof T]: T[K] extends string ? string : WidenStrings<T[K]>;
};

