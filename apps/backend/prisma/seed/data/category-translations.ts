/**
 * Tohumlayıcının `nameTranslations` sütununa yazacağı sözlüğü kurar.
 *
 * Türkçe her zaman yazılır; İngilizce karşılık yoksa sözlükte yalnızca `tr`
 * kalır ve istemci İngilizce arayüzde Türkçe adı gösterir.
 */
export function catalogNameTranslations(slug: string, turkishName: string): Record<string, string> {
  const english = CATALOG_NAMES_EN[slug];

  return english ? { tr: turkishName, en: english } : { tr: turkishName };
}
